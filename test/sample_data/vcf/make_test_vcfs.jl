# julia --project=. test/sample_data/vcf/make_test_vcfs.jl [--check]
isdefined(@__MODULE__, :vtest_fasta) || include(joinpath(@__DIR__, "..", "..", "helpers", "vcf.jl"))
isdefined(@__MODULE__, :vfixture_cases) || include(joinpath(@__DIR__, "cases.jl"))

function write_vcf_fixtures(destination)
    mkpath(destination)
    reference = joinpath(@__DIR__, "..", "genome", "semirandom.fa")
    sequence = open(FASTA.Reader, reference) do reader
        string(FASTA.sequence(LongDNA{4}, first(reader)))
    end
    pam = findfirst(i -> sequence[i + 1:i + 2] == "GG" &&
        all(c -> c in "ACGT", sequence[i - 20:i + 2]), 1000:(length(sequence) - 2)) + 999
    positions = [pam - 15, pam - 10, pam - 5]
    records = [
        (positions[1], "snp", sequence[positions[1]:positions[1]], sequence[positions[1]] == 'A' ? "C" : "A"),
        (positions[2], "ins", sequence[positions[2]:positions[2]], sequence[positions[2]:positions[2]] * "C"),
        (positions[3], "del", sequence[positions[3]:positions[3] + 1], sequence[positions[3]:positions[3]]),
    ]
    vtest_vcf(joinpath(destination,"small_norm.vcf"),
        [("semirandom1", row..., ".", "PASS", ".") for row in records]; header=["##reference=semirandom.fa"])
    write(joinpath(destination,"guide.txt"), sequence[pam - 20:pam - 1] * "\n")
    for folder in ("valid", "invalid", "references", "guides")
        mkpath(joinpath(destination,folder))
    end
    index = ["# VCF fixtures", "", "Generated by `make_test_vcfs.jl`; edit `cases.jl` and regenerate.",
        "Run `julia --project=. test/sample_data/vcf/make_test_vcfs.jl --check` to verify reproducibility.",
        "", "`small_norm.vcf` and `guide.txt` use `../genome/semirandom.fa`.",
        "Each sequence case below has `valid/ID.vcf`, `references/ID.fa` (with FAI), and `guides/ID.txt`.",
        "`annotations` and `ignored_markers` use `references/contracts.fa` and `guides/mixed_choices.txt`.",
        "Edits and required witness alleles are explicit in `cases.jl`. Expected result sets come from the independent test oracle, never from the VCF scanner.",
        "", "| ID | Checklist | Motif / distance | Required ALT IDs | Purpose |", "|---|---|---|---|---|"]
    for case in vfixture_cases()
        vtest_fasta(joinpath(destination,"references",case.id*".fa"), [case.chrom=>case.reference])
        vtest_vcf(joinpath(destination,"valid",case.id*".vcf"), vtest_records(case.edits;chrom=case.chrom))
        write(joinpath(destination,"guides",case.id*".txt"), join(string.(case.guides),'\n')*"\n")
        push!(index,"| $(case.id) | $(case.requirement) | $(case.motif) / $(case.distance) | $(join(case.witness,", ")) | $(case.purpose) |")
    end
    vtest_fasta(joinpath(destination,"references","contracts.fa"), ["chr1"=>VCF_TEST_REFERENCE,"chr2"=>VCF_TEST_REFERENCE])
    for case in vfixture_contracts()
        vtest_vcf(joinpath(destination,"valid",case.id*".vcf"),case.records;header=case.header,samples=case.samples)
        push!(index,"| $(case.id) | V03 / V10 | Cas9 / 1 | See input-contract assertions | Metadata/marker contract on references/contracts.fa |")
    end
    append!(index,["", "Invalid cases use `references/contracts.fa` and the guide from `guides/mixed_choices.txt`.",
        "Each file has one intended fault. Unsupported symbolic alleles are rejection tests, not SV support.",
        "", "| Invalid ID | Expected error fragment |", "|---|---|"])
    for case in vfixture_invalid()
        vtest_vcf(joinpath(destination,"invalid",case.id*".vcf"),case.records)
        push!(index,"| $(case.id) | $(case.message) |")
    end
    write(joinpath(destination,"README.md"),join(index,'\n')*"\n")
end

function check_vcf_fixtures()
    mktempdir() do temporary
        write_vcf_fixtures(temporary)
        for (root,_,files) in walkdir(temporary), file in files
            relative=relpath(joinpath(root,file),temporary)
            target=joinpath(@__DIR__,relative)
            isfile(target) && read(target)==read(joinpath(root,file)) || error("Stale VCF fixture: $relative")
        end
        for folder in ("valid","invalid","references","guides")
            sort(readdir(joinpath(@__DIR__,folder)))==sort(readdir(joinpath(temporary,folder))) || error("Unexpected files in $folder")
        end
    end
    println("VCF fixtures match their definitions.")
end

if abspath(PROGRAM_FILE) == @__FILE__
    isempty(ARGS) ? write_vcf_fixtures(@__DIR__) : ARGS == ["--check"] ? check_vcf_fixtures() : error("Expected no arguments or --check")
end
